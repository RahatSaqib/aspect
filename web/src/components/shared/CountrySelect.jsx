import React from 'react'
import _ from 'lodash'
import SelectField from 'material-ui/SelectField'
import MenuItem from 'material-ui/MenuItem'
import FlagIcon from './flagIcon/FlagIcon'

const MenuItemLabel = props => {
  const {country, selectedItemStyle} = props
  return <div style={{...{display: 'inline-block', whiteSpace: 'nowrap', overflow: 'hidden'}, ...selectedItemStyle}}>
    <FlagIcon countryIsoAlpha2Code={country.iso_alpha2_code} />
    <div style={{position: 'absolute', left: '1.3em', right: '1.4em', top: '0.15em', textAlign: 'right', whiteSpace: 'nowrap', overflow: 'hidden'}}>
      {country.selectedItemText}
    </div>
  </div>
}

export default props => {
  const {value, selectFieldStyle, selectedItemStyle, underlineStyle, onChange} = props,
    dataSource = props.dataSource || countries,
    dataSourceConfig = props.dataSourceConfig || {},
    countriesJoinOn = dataSourceConfig.countriesJoinOn || 'iso_alpha2_code',
    dataSourceJoinOn = dataSourceConfig.dataSourceJoinOn || 'iso_alpha2_code',
    menuItemTextPredicate = dataSourceConfig.menuItemTextPredicate || (country => country.name),
    selectedItemTextPredicate = dataSourceConfig.selectedItemTextPredicate || (country => country.name),
    valuePredicate = dataSourceConfig.valuePredicate || (country => country.iso_alpha2_code),
    validDataSourceCountries = _.filter(dataSource, dataSourceCountry =>
      _.some(countries, country => country[countriesJoinOn] === dataSourceCountry[dataSourceJoinOn])),
    countriesData = _.map(validDataSourceCountries,
      dataSourceCountry => {
        const matchingCountry = _.find(countries, country => country[countriesJoinOn] === dataSourceCountry[dataSourceJoinOn]),
          mergedCountry = {...matchingCountry, ...dataSourceCountry}
        return {
          iso_alpha2_code: mergedCountry.iso_alpha2_code,
          name: mergedCountry.name,
          value: valuePredicate(mergedCountry),
          menuItemText: menuItemTextPredicate(mergedCountry),
          selectedItemText: selectedItemTextPredicate(mergedCountry)
        }
      })

  return <SelectField value={value} style={selectFieldStyle} underlineStyle={underlineStyle}
                      autoWidth={true} onChange={onChange}>
    {
      countriesData.map(country =>
        <MenuItem key={country.value} value={country.value}
                  primaryText={country.menuItemText} leftIcon={<FlagIcon style={{margin: '0.3em 0'}} countryIsoAlpha2Code={country.iso_alpha2_code} />}
                  label={<MenuItemLabel country={country} selectedItemStyle={selectedItemStyle} />} />)
    }
  </SelectField>
}

